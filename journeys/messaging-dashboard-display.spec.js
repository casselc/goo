const { test, expect } = require('@playwright/test');
const { base, json, seed, observe, loaded, snapshot, write } = require('./190-messaging-dashboard-support');
const { profileLayout } = require('./190-profile-layout');
test.use({ actionTimeout: 15000, navigationTimeout: 45000 });
test('190 profile labels stay readable in mobile two-column layout without extra reads', async ({ page, request }) => {
  test.setTimeout(120000);
  const facts = await seed(request), observation = observe(page);
  await page.goto(base + '/#services'); await page.locator('#inventoryEnvironment').fill(facts.environment); await page.locator('#minutes').fill('2');
  await page.locator('#inventoryRun').click();
  await expect(page.getByRole('button', { name: 'Open service commerce / messaging-app', exact: true })).toBeVisible();
  const planning = page.waitForResponse(response => response.url().endsWith('/api/dashboards/plan'));
  await page.getByRole('button', { name: 'Open service commerce / messaging-app', exact: true }).click();
  const plan = await json(await planning), dash = await loaded(page, 'messaging-consumer'), before = await snapshot(page, observation);
  expect(before.evidence.find(item => item.widget.key === 'spans').count).toBe('137');
  expect(observation.source).toBe(9); expect(observation.plans).toBe(1);
  await page.setViewportSize({ width: 1440, height: 1800 }); const desktop = await profileLayout(page);
  await page.getByRole('heading', { name: 'Services', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'docs/journeys/screenshots/190c-messaging-service-in-context.png' });
  await dash.screenshot({ path: 'docs/journeys/screenshots/190a-messaging-consumer-dashboard.png' });
  await page.setViewportSize({ width: 390, height: 1600 }); const mobile = await profileLayout(page, true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('heading', { name: 'Services', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'docs/journeys/screenshots/190d-mobile-messaging-in-context.png' });
  await dash.locator('[data-widget=spans]').screenshot({ path: 'docs/journeys/screenshots/190b-mobile-consumer-summary.png' });
  expect(observation.source).toBe(9); expect(observation.plans).toBe(1);
  expect((await snapshot(page, observation)).evidence).toEqual(before.evidence);
  expect(observation.errors).toEqual([]);
  observation.event('responsive-profile-display', { sourceFreeResize: true });
  await write(facts, 'display.json', { ...facts, plan, before, desktop, mobile, events: observation.events, requests: observation.requests, responses: observation.responses });
});
