// These consumer checks exercise the upstream tangler and diagnostic mapping;
// they do not implement a second extraction or source-position convention.
func TestLiterateAcquisitionDiagnostics(t *testing.T) {
	for _, tc := range []struct {
		name, expression string
	}{
		{"broken-invariant", "false"},
		{"unknown-name", "CW1MissingSymbol"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			b := copyBinding(t)
			doc := filepath.Join(filepath.Dir(b), "model", "acquisition.md")
			raw, err := os.ReadFile(doc)
			if err != nil {
				t.Fatal(err)
			}
			const declaration = "  val retainedOwnership = safe"
			if strings.Count(string(raw), declaration) != 1 {
				t.Fatal("expected one authored retainedOwnership declaration")
			}
			line := strings.Count(string(raw[:strings.Index(string(raw), declaration)]), "\n") + 1
			mutated := strings.Replace(string(raw), declaration, "  val retainedOwnership = "+tc.expression, 1)
			if err := os.WriteFile(doc, []byte(mutated), 0644); err != nil {
				t.Fatal(err)
			}
			want := fmt.Sprintf("acquisition.md:%d", line)
			checker, err := validate.NewChecker(context.Background(), b, options())
			if tc.name == "unknown-name" {
				if checker != nil {
					checker.Close()
				}
				if err == nil || !strings.Contains(err.Error(), want+":") || !strings.Contains(err.Error(), "CW1MissingSymbol") {
					t.Fatalf("expected authored typecheck diagnostic at %s, got %v", want, err)
				}
				t.Logf("typecheck diagnostic names %s", want)
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			defer checker.Close()
			log, err := qdriver.ReadFile("testdata/cw1/requests.jsonl")
			if err != nil {
				t.Fatal(err)
			}
			steps, err := Steps(log)
			if err != nil {
				t.Fatal(err)
			}
			report, err := checker.Check(context.Background(), steps)
			if err != nil {
				t.Fatal(err)
			}
			if report.Finished().Verdict != validate.Fail {
				t.Fatalf("broken invariant did not fail: %+v", report.Finished())
			}
			if !strings.Contains(report.Summary(), "invariant retainedOwnership (") || !strings.Contains(report.Summary(), want+"): FAIL") {
				t.Fatalf("failure missing authored source position %s:\n%s", want, report.Summary())
			}
			t.Logf("actual acquisition log violates broken invariant at %s", want)
		})
	}
}

func tangleCommand(t *testing.T, wantCode int, args ...string) string {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", append([]string{"tool", "gotogether", "tangle"}, args...)...)
	out, err := cmd.CombinedOutput()
	code := 0
	if err != nil {
		exit, ok := errors.AsType[*exec.ExitError](err)
		if !ok {
			t.Fatalf("running pinned gotogether tool: %v: %s", err, out)
		}
		code = exit.ExitCode()
	}
	if code != wantCode {
		t.Fatalf("tangle %v: exit %d, want %d: %v\n%s", args, code, wantCode, err, out)
	}
	return string(out)
}

func TestLiterateAcquisitionFreshness(t *testing.T) {
	b := copyBinding(t)
	doc := filepath.Join(filepath.Dir(b), "model", "acquisition.md")
	generated := strings.TrimSuffix(doc, ".md") + ".qnt"
	tangleCommand(t, 0, "-check", doc)
	raw, err := os.ReadFile(doc)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(doc, append(raw, []byte("\nA deliberately changed explanation.\n")...), 0644); err != nil {
		t.Fatal(err)
	}
	if out := tangleCommand(t, 1, "-check", doc); !strings.Contains(out, "stale") {
		t.Fatalf("stale generated model lacked the expected diagnosis: %s", out)
	}
	tangleCommand(t, 0, doc)
	tangleCommand(t, 0, "-check", doc)
	if err := os.Remove(generated); err != nil {
		t.Fatal(err)
	}
	if out := tangleCommand(t, 1, "-check", doc); !strings.Contains(out, "missing") {
		t.Fatalf("missing generated model lacked the expected diagnosis: %s", out)
	}
	const handWritten = "// a hand-written sibling must not be replaced\nmodule local {}\n"
	if err := os.WriteFile(generated, []byte(handWritten), 0644); err != nil {
		t.Fatal(err)
	}
	if out := tangleCommand(t, 2, doc); !strings.Contains(out, "not generated by gotogether") {
		t.Fatalf("hand-written model lacked overwrite refusal: %s", out)
	}
	retained, err := os.ReadFile(generated)
	if err != nil || string(retained) != handWritten {
		t.Fatalf("hand-written sibling changed: %v: %q", err, retained)
	}
}
